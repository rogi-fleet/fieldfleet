/// 4px-grid spacing tokens for the FieldFleet design system.
abstract final class AppSpacing {
  // ── Raw scale ──────────────────────────────────────────
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double base = 16;
  static const double lg = 20;
  static const double xl = 24;
  static const double xxl = 32;
  static const double xxxl = 48;

  // ── Semantic aliases ───────────────────────────────────
  static const double cardPadding = lg;
  static const double sectionGap = xl;
  static const double screenPaddingMobile = base;
  static const double screenPaddingTablet = lg;
  static const double screenPaddingDesktop = xl;
  static const double iconGap = md;
  static const double inputGap = sm;
}
